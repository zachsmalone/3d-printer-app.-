def test_placed_gcode_is_not_centered_again(monkeypatch, tmp_path):
    seen = {}

    def fake_run(cmd, **_kw):
        seen["cmd"] = cmd
        out = cmd[cmd.index("--output") + 1]

        class Proc:
            returncode = 0
            stdout = ""
            stderr = ""

        open(out, "w", encoding="utf-8").write("; estimated printing time (normal mode) = 1s\n; filament used [g] = 1\n")
        return Proc()

    monkeypatch.setattr(subprocess, "run", fake_run)
    ini = tmp_path / "a.ini"
    ini.write_text("nozzle_diameter = 0.4\n")
    model = tmp_path / "m.3mf"
    model.write_bytes(b"PK")
    out = tmp_path / "o.gcode"
    eng.run_engine("/usr/bin/prusa-slicer", ini, model, out, placed=True)
    assert "--dont-arrange" in seen["cmd"]
    assert "--center" not in seen["cmd"]
    eng.run_engine("/usr/bin/prusa-slicer", ini, model, out, placed=False)
    assert "--center" in seen["cmd"]
    assert "--dont-arrange" not in seen["cmd"]


def _model_extrusion(text: str) -> dict[int, float]:
    """Millimetres extruded on each tool outside the wipe tower."""
    tool = 0
    kind = ""
    relative = True
    absolute = 0.0
    out = {0: 0.0, 1: 0.0}
    for line in text.splitlines():
        if line.startswith(";TYPE:"):
            kind = line.split(":", 1)[1].strip().lower()
            continue
        bare = line.split(";", 1)[0].strip()
        if not bare:
            continue
        upper = bare.upper()
        if upper.startswith("M83"):
            relative = True
            continue
        if upper.startswith("M82"):
            relative = False
            continue
        if upper.startswith("G92") and re.search(r"\bE", upper):
            absolute = 0.0
            continue
        tool_m = re.match(r"T(\d+)\b", bare, re.I)
        if tool_m:
            tool = int(tool_m.group(1))
            continue
        if not upper.startswith(("G0", "G1")):
            continue
        found = re.search(r"\bE([+-]?\d*\.?\d+)", bare, re.I)
        if not found:
            continue
        value = float(found.group(1))
        delta = value if relative else max(0.0, value - absolute)
        if not relative:
            absolute = value
        if delta > 0 and kind != "wipe tower" and tool in out:
            out[tool] += delta
    return out


@pytest.mark.skipif(_prusa_exe() is None, reason="PrusaSlicer CLI is not installed")
def test_prusaslicer_two_slots_toolchange_and_one_slot_does_not(client):
    bid, parts = _open(client)
    _assign(client, bid, parts[0]["id"], 1)
    _assign(client, bid, parts[1]["id"], 2)
    fast = {"layer_height": "0.3", "walls": "1", "top_bottom": "1", "infill": "0", "supports": "off"}
    body = _slice(client, bid, **fast)
    assert body["multi_extruder"] is True
    assert body["multi_extruder_label"] == PRINT_NOTE
    assert "Not yet tested on a printer." in body["multi_extruder_label"]
    text = client.get(body["gcode_url"]).text
    assert "Not yet tested on a printer." in text
    assert "; ZEIM part Left: slot 1 extruder 1" in text
    assert "; ZEIM part Right: slot 2 extruder 2" in text
    assert re.search(r"^T0\b", text, re.M)
    assert re.search(r"^T1\b", text, re.M)
    assert ";TYPE:Wipe tower" in text
    used = re.search(r"filament used \[mm\] = ([0-9., ]+)", text)
    assert used
    amounts = [float(x) for x in used.group(1).replace(" ", "").split(",") if x]
    assert len(amounts) >= 2 and amounts[0] > 0 and amounts[1] > 0
    extruded = _model_extrusion(text)
    assert extruded[0] > 0 and extruded[1] > 0, extruded

    _assign(client, bid, parts[1]["id"], 1)
    single = _slice(client, bid, **fast)
    assert single["multi_extruder"] is False and single["single_slot"] is False
    single_text = client.get(single["gcode_url"]).text
    assert not re.search(r"^T1\b", single_text, re.M)
    assert ";TYPE:Wipe tower" not in single_text
    assert "Not yet tested on a printer." not in single_text
    assert "no tool changes" in single_text
