    _assign(client, bid, parts[0]["id"], 1)
    _assign(client, bid, parts[1]["id"], 2)
    body = _slice(client, bid)
    assert body["multi_extruder"] is True
    assert body["multi_extruder_label"] == PRINT_NOTE
    assert body["multi_fallback"] == ""
    assert body["single_slot"] is False
    assert [(p["name"], p["slot"]) for p in body["part_extruders"]] == [("Left", 1), ("Right", 2)]
