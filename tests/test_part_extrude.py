def _open(client, printer="bambu_x1c"):
    opened = client.post(
        "/api/edit/new",
        files={"file": ("apart.3mf", _apart_3mf(), "model/3mf")},
        data={"printer_id": printer},
    )
    assert opened.status_code == 200, opened.text
    body = opened.json()
    return body["id"], body["parts"]


def _assign(client, bid, part_id, slot, count=4):
    got = client.put(f"/api/edit/{bid}/parts/slots", json={
        "action": "assign", "ids": [part_id], "slot": slot, "slot_count": count,
    })
    assert got.status_code == 200, got.text
    return got.json()["parts"]


def _slice(client, bid, **form):
    data = {"model_id": bid, "printer_id": "bambu_x1c", "nozzle": "0.4"}
    data.update(form)
    got = client.post("/api/slice", data=data)
    assert got.status_code == 200, got.text
    return got.json()


