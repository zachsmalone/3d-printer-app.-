"""Per-part slots become a PrusaSlicer multi-extruder slice.

A printer with a multi-material unit and two part slots gets a 3MF plus one copy
of that profile's filament settings per slot, a wipe tower, and tool changes.
One slot, including the skip-calibration switch, stays on today's path.
A printer with no multi-material unit, or a profile that is not one nozzle and
not exactly those slots, slices as one colour.

The real PrusaSlicer run is skipped when the CLI is not installed. Nothing here
is sent to a printer.
"""
