    assert _ini_value(ini, "single_extruder_multi_material") == "1"
    assert _ini_value(ini, "wipe_tower") == "1"
    assert fake_engine[0]["placed"] is True
    assert str(fake_engine[0]["model"]).endswith("model_parts.3mf")
    files = _files(fake_engine[0]["model"].read_bytes())
    assert 'key="extruder" value="1"' in files["Metadata/Slic3r_PE_model.config"]
    assert 'key="extruder" value="2"' in files["Metadata/Slic3r_PE_model.config"]
    gcode = client.get(body["gcode_url"]).text
    assert "Not yet tested on a printer." in gcode
    assert "; ZEIM part Left: slot 1 extruder 1" in gcode
    assert "; ZEIM part Right: slot 2 extruder 2" in gcode
    assert "T0" in gcode and "T1" in gcode
    saved = _files(client.get(body["downloads"]["3mf"]).content)
    assert 'key="extruder" value="2"' in saved["Metadata/Slic3r_PE_model.config"]


