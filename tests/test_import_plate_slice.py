def _apart_3mf():
    left = _box((10, 10, 10), (0, 0, 5))
    right = _box((10, 10, 10), (40, 0, 5))
    return _3mf(
        [_mesh_xml(left, 1, "Left"), _mesh_xml(right, 2, "Right")],
        ['<item objectid="1"/>', '<item objectid="2"/>'],
    )


def _open(client, name, data, mime):
    opened = client.post("/api/edit/new", files={"file": (name, data, mime)})
    assert opened.status_code == 200, opened.text
    body = opened.json()
    meta = store.get(body["id"])
    layout = (meta.get("plate_layouts") or {}).get(str(meta.get("head")))
    assert layout and len(layout["counts"]) >= 2
    return body["id"]


def _slice(client, model_id):
    return client.post("/api/slice", data={"model_id": model_id, "printer_id": "creality_k1", "nozzle": "0.4"})


def test_imported_parts_slice_as_one_stl_until_they_are_arranged(client, fake_engine):
    apart = _open(client, "apart.3mf", _apart_3mf(), "model/3mf")
    coloured = _open(client, "colour.3mf", _coloured_3mf(), "model/3mf")
    prof = eng.get_profile("creality_k1")
    objs, _skipped = slice_api.plate_on_bed(coloured, prof)
    assert objs and len(objs) >= 2 and slice_api.bounds_intersect(objs)

    for model_id in (apart, coloured):
        fake_engine.clear()
        got = _slice(client, model_id)
        assert got.status_code == 200, got.text
        assert got.json()["plate_objects"] == 1
        assert fake_engine["parts"] is None
        assert fake_engine["model"] == "model.stl"


def test_arranged_plate_still_slices_as_separate_objects(client, fake_engine):
    files = [("files", (f"p{i}.stl", trimesh.creation.box((20, 20, 10)).export(file_type="stl"), "model/stl")) for i in range(4)]
    made = client.post("/api/edit/multi", files=files, data={"mode": "plate", "printer_id": "creality_k1"})
    assert made.status_code == 200, made.text
    pid = made.json()["projects"][0]
    arranged = client.post(f"/api/edit/{pid}/op", json={"op": "plate", "params": {"action": "arrange", "gap": 10, "printer_id": "creality_k1"}})
    assert arranged.status_code == 200, arranged.text
    got = _slice(client, pid)
    assert got.status_code == 200, got.text
    assert got.json()["plate_objects"] == 4
    assert fake_engine["parts"] is not None and len(fake_engine["parts"]) == 4
    assert [p.name for p in fake_engine["parts"]] == ["part_01.stl", "part_02.stl", "part_03.stl", "part_04.stl"]


def _png(i):
    im = Image.fromarray((np.random.default_rng(i).random((24, 32, 3)) * 255).astype("uint8"))
    buf = io.BytesIO()
    im.save(buf, "PNG")
    return (f"p{i}.png", buf.getvalue(), "image/png")


def test_memory_box_parts_stay_separate_objects(client, fake_engine):
    files = [("files", _png(i)) for i in range(4)]
    # Small enough that several laid-out parts sit inside the centred bed. A 60 mm box
    # starts at the origin, so only one part is fully on a 220 mm bed and the rest are skipped.
    made = client.post("/api/memorybox", files=files, data={
        "style": "frame", "panel_mm": "50", "photo_ack": "true", "base": "false",
        "hole_preset": "custom", "hole_w": "15", "notch_mm": "0",
    })
    assert made.status_code == 200, made.text
    edit = client.post("/api/edit/new", data={"from_build": made.json()["id"], "beginner": "true"})
    assert edit.status_code == 200, edit.text
    body = edit.json()
    assert body["base"]["from_mode"] == "memorybox"
    got = _slice(client, body["id"])
    assert got.status_code == 200, got.text
    count = got.json()["plate_objects"]
    assert count >= 2
    assert fake_engine["parts"] is not None and len(fake_engine["parts"]) == count


def test_decision_joins_imports_and_any_overlap_and_keeps_arranged_parts(monkeypatch):
    a = trimesh.creation.box((10, 10, 10))
    b = a.copy()
    b.apply_translation((40, 0, 0))
    peg = a.copy()
    peg.apply_translation((4, 0, 0))
    saved = {}
    monkeypatch.setattr(slice_api.store, "get", lambda bid: saved[bid])

    saved["import"] = {"head": 0, "ops": [], "base": {"type": "upload", "format": "3mf"}}
    assert slice_api.bounds_intersect([a, b]) is False
    assert slice_api.separate_plate_objects("import", [a, b]) is False

    saved["overlap"] = {"head": 1, "ops": [{"op": "plate"}], "base": {"type": "upload"}}
    assert slice_api.bounds_intersect([a, peg]) is True
    assert slice_api.separate_plate_objects("overlap", [a, peg]) is False

    saved["plate"] = {"head": 1, "ops": [{"op": "plate"}], "base": {"type": "plate"}}
    assert slice_api.separate_plate_objects("plate", [a, b]) is True

    saved["box"] = {"head": 0, "ops": [], "base": {"type": "build", "from_mode": "memorybox"}}
    assert slice_api.arranged_on_bed(saved["box"]) is True
    assert slice_api.separate_plate_objects("box", [a, b]) is True

    saved["undone"] = {"head": 0, "ops": [{"op": "plate"}], "base": {"type": "upload"}}
    assert slice_api.arranged_on_bed(saved["undone"]) is False


@pytest.mark.skipif(not HAVE_SLICER, reason="PrusaSlicer not installed")
def test_coloured_multiobject_3mf_slices(client):
    model_id = _open(client, "colour.3mf", _coloured_3mf(), "model/3mf")
    got = _slice(client, model_id)
    assert got.status_code == 200, got.text
    body = got.json()
    assert body["plate_objects"] == 1
    assert body["print_time_seconds"] and body["filament_grams"]
    gcode = client.get(body["gcode_url"]).text
    assert "G1" in gcode and ";LAYER_CHANGE" in gcode
