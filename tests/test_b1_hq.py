# ---------------------------------------------------------------- #3 pop-art non-manifold layers (root cause)
def _max_edge_faces(v, f):
    import numpy as np
    e = np.sort(np.concatenate([f[:, [0, 1]], f[:, [1, 2]], f[:, [2, 0]]]), axis=1)
    _, cnt = np.unique(e, axis=0, return_counts=True)
    return int(cnt.max())


def test_hq3_fix_checkers_handles_both_diagonals_and_extrusion_is_manifold():
    import numpy as np
    from app.core import geometry as g
    for m in (np.array([[0, 1], [1, 0]], bool), np.array([[1, 0], [0, 1]], bool)):
        fixed = g.fix_checkers(m)
        assert (fixed | m).sum() == fixed.sum() and fixed.sum() == 3            # one cell added, nothing removed
        v, f = g.prism_mask_solid(fixed, 1.0, 0.0, 1.0)[:2]
        assert _max_edge_faces(v, f) == 2
    rng = np.random.default_rng(7)
    for n in range(60):                                                         # random checkerboard-ish masks
        m = rng.random((24, 31)) < 0.5
        fixed = g.fix_checkers(m)
        assert (fixed | m == fixed).all()
        v, f = g.prism_mask_solid(fixed, 0.5, 0.0, 1.0)[:2]
        assert _max_edge_faces(v, f) <= 2, n
    # the unfixed mask really was broken (guards the test itself)
    v, f = g.prism_mask_solid(np.array([[0, 1], [1, 0]], bool), 1.0, 0.0, 1.0)[:2]
    assert _max_edge_faces(v, f) == 4


