@needs_slicer
def test_hq1_slice_uses_the_build_that_was_asked_for_after_expert_rebuild():
    c = client()
    beg = build(c, beginner="true", width_mm="100")                                    # Beginner first ...
    exp = build(c, beginner="false", width_mm="40", min_thickness="1.2", max_thickness="2.0", border_mm="1")   # ... then an Expert rebuild
    assert beg["id"] != exp["id"]
    def sliced(b):
        r = c.post(f"/api/slice/{b['id']}", data={"layer_height": "0.2", "fill_density": "15", "upright": "true"}).json(); assert r["ok"], r
        return r, (config.OUT / b["id"] / "model.gcode").read_text()
    rb, gb = sliced(beg); re_, ge = sliced(exp)
    # upright lithophane: layer count follows the model's HEIGHT, so the two builds must differ clearly
    hb, he = beg["stats"]["size_mm"][1], exp["stats"]["size_mm"][1]
    assert abs(rb["layers"] - hb / 0.2) <= 3 and abs(re_["layers"] - he / 0.2) <= 3
    assert rb["layers"] != re_["layers"] and gb != ge
    # each build's G-code lives in its own folder; slicing one never touches the other
    assert (config.OUT / beg["id"] / "model.gcode").exists() and (config.OUT / exp["id"] / "model.gcode").exists()
    # send/links are bound to the id given in the URL too
    assert c.get(f"/api/print/{exp['id']}/links").json()["slicers"][0]["url"].count(exp["id"]) >= 1
    assert beg["id"] not in c.get(f"/api/print/{exp['id']}/links").json()["slicers"][0]["url"]


