import pytest
from fastapi.testclient import TestClient
from app.services import gcode_layers as gl

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PRUSA_STYLE = """; generated by PrusaSlicer
M83 ; relative E
G28
G1 Z0.2 F600
;LAYER_CHANGE
;Z:0.2
;HEIGHT:0.2
G92 E0
;TYPE:Skirt/brim
G1 X10 Y10 F9000
G1 X20 Y10 E0.5
G1 X20 Y20 E0.5
G1 E-0.8 ; retract
G1 X50 Y50 ; travel
G1 E0.8 ; unretract (no XY: not a line)
;TYPE:External perimeter
G1 X60 Y50 E0.4
G1 X60 Y60 E0.4
;TYPE:Internal infill
G1 X50 Y60 E0.4
;LAYER_CHANGE
;Z:0.4
;HEIGHT:0.2
G1 Z0.8 ; z hop inside the layer change
G1 X50 Y50
G1 Z0.4
;TYPE:Perimeter
G1 X55 Y50 E0.2
G1 Z0.8 ; hop
G1 X58 Y58
G1 Z0.4
;TYPE:Support material
G1 X58 Y59 E0.1
M104 S0
"""

ABS_STYLE = """M82
G90
G1 Z0.3 X0 Y0
G1 X10 Y0 E1
G1 X10 Y10 E2
G1 X10 Y10 E1.5 ; retract (E down)
G1 X0 Y10 E1.5 ; travel (E same)
G92 E0
G1 X0 Y0 E0.5
G1 Z0.6
G1 X5 Y5 E1.0
G91
G1 X1 E0.2 ; relative: X 6, extrudes
G90
"""


def test_prusa_style_layers_kinds_and_skips():
    r = gl.parse(PRUSA_STYLE)
    assert [l["z"] for l in r["layers"]] == [0.2, 0.4]                  # z hops inside a layer do not start new layers
    l0 = r["layers"][0]["paths"]
    assert [p["k"] for p in l0] == ["skirt", "outer", "infill"]
    assert l0[0]["p"] == [10, 10, 20, 10, 20, 20]                      # the travel to 50,50 is not a line
    assert l0[1]["p"] == [50, 50, 60, 50, 60, 60] and l0[2]["p"] == [60, 60, 50, 60]
    l1 = r["layers"][1]["paths"]
    assert [p["k"] for p in l1] == ["inner", "support"] and l1[1]["p"] == [58, 58, 58, 59]
    assert r["bounds"] == [10, 10, 60, 60] and r["kinds"]["outer"] == "Outer wall" and not r["thinned"]


def test_absolute_e_g92_and_g91_without_markers():
    r = gl.parse(ABS_STYLE)
    assert [l["z"] for l in r["layers"]] == [0.3, 0.6]
    assert r["layers"][0]["paths"][0]["p"] == [0, 0, 10, 0, 10, 10]
    assert r["layers"][0]["paths"][1]["p"] == [0, 10, 0, 0]              # after G92 E0 the next E0.5 extrudes again
    assert r["layers"][1]["paths"][0]["p"] == [0, 0, 5, 5, 6, 5]         # G91 relative move continues the line


def test_thinning_keeps_ends_and_budget():
    lines = ["M83", "G1 Z0.2"] + [f"G1 X{i % 100} Y{(i // 100) % 2} E0.01" for i in range(1, 5001)]
    r = gl.parse("\n".join(lines), max_points=500)
    assert r["thinned"] and r["points"] <= 600
    p = r["layers"][0]["paths"][0]["p"]
    assert p[:2] == [0, 0] and p[-2:] == [0, 0]                         # first and last points kept


def test_no_lines_is_a_friendly_error():
    with pytest.raises(gl.GcodeError):
        gl.parse("G28\nG1 X10 Y10\nM84\n")


def test_layers_endpoint_from_a_real_slice():
    if not shutil.which("prusa-slicer") and not shutil.which("PrusaSlicer"):
        pytest.skip("PrusaSlicer not installed")
    from app.main import app
    from app.api import slice as sl
    c = TestClient(app)
    with open(os.path.join(ROOT, "static", "sample_model.stl"), "rb") as f:
        r = c.post("/api/slice", files={"file": ("m.stl", f.read(), "model/stl")})
    assert r.status_code == 200, r.text
    j = r.json(); sid = j["slice_id"]
    assert j["downloads"]["layers"] == f"/api/slice/{sid}/layers"
    g = c.get(f"/api/slice/{sid}/layers")
    assert g.status_code == 200
    d = g.json()
    assert len(d["layers"]) > 100 and d["layers"][0]["z"] == pytest.approx(0.2) and d["points"] <= gl.MAX_POINTS
    assert {"outer", "inner", "infill"} <= {p["k"] for l in d["layers"] for p in l["paths"]}
    assert (sl.slices_root() / sid / "layers.json.gz").is_file()                  # cached for the next request
    assert json.loads(gzip.decompress((sl.slices_root() / sid / "layers.json.gz").read_bytes()))["points"] == d["points"]
    gz = c.get(f"/api/slice/{sid}/layers", headers={"Accept-Encoding": "gzip"})
    assert gz.status_code == 200 and gz.json()["points"] == d["points"]
    assert c.get("/api/slice/../../etc/layers").status_code == 404
    assert c.get("/api/slice/" + "0" * 32 + "/layers").status_code == 404


