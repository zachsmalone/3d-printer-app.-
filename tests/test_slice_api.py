@pytest.mark.skipif(eng.find_engine() is None, reason="PrusaSlicer not installed")
def test_real_prusaslicer_smoke(client, tmp_path):
    cube = tmp_path / "cube.stl"
    v = [(0, 0, 0), (20, 0, 0), (20, 20, 0), (0, 20, 0), (0, 0, 20), (20, 0, 20), (20, 20, 20), (0, 20, 20)]
    f = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
         (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    data = b"\0" * 80 + struct.pack("<I", len(f))
    for a, b, c in f:
        data += struct.pack("<12fH", 0, 0, 0, *v[a], *v[b], *v[c], 0)
    cube.write_bytes(data)
    r = client.post("/api/slice", files={"file": ("cube.stl", data)})
    assert r.status_code == 200, r.text
    assert r.json()["filament_grams"] and r.json()["print_time_seconds"]
