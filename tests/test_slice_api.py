def make_build(tmp_path, bid, owner_sid, visibility="private"):
    import json
    d = tmp_path / "outputs" / bid
    d.mkdir()
    (d / "meta.json").write_text(json.dumps({"id": bid, "owner_sid": owner_sid, "visibility": visibility, "created": 0}))
    write_box_stl(d / "model.stl", 30, 30, 30)


def sid_of(client):
    from app.community.identity import COOKIE
    client.get("/api/slice/profiles")
    sid = client.cookies.get(COOKIE)
    if not sid:
        sid = "s" * 32
        client.cookies.set(COOKIE, sid)
    return sid


@pytest.fixture
def fake_engine(monkeypatch):
    calls = []

    def fake_run(engine, ini, stl, out, timeout=0):
        calls.append((ini.read_text(), stl))
        out.write_text(SAMPLE_GCODE)

    monkeypatch.setattr(eng, "find_engine", lambda: "/usr/bin/fake-prusa-slicer")
    monkeypatch.setattr(eng, "run_engine", fake_run)
    return calls


def upload(client, tmp_path, x, y, z, name="m.stl", **form):
    stl = write_box_stl(tmp_path / "up.stl", x, y, z)
    return client.post("/api/slice", files={"file": (name, stl.read_bytes())}, data=form)


def test_upload_success_and_download(client, fake_engine, tmp_path):
    r = upload(client, tmp_path, 50, 50, 20)
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["print_time_seconds"] == 5025 and body["print_time_human"] == "1h 23m"
    assert body["filament_grams"] == 12.0
    assert body["profile"] == "creality_k1"
    assert body["model_size_mm"] == [50, 50, 20]
    assert "nozzle_diameter = 0.4" in fake_engine[0][0]
    g = client.get(body["gcode_url"])
    assert g.status_code == 200 and "total filament used" in g.text


