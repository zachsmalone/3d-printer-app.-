use crate::defs::{LENGTH_EPS, VERY_POSITIVE};

/// A quaternion a + (vx)*i + (vy)*j + (vz)*k (translated from `Quaternion`).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Quaternion {
    pub w: f64,
    pub vx: f64,
    pub vy: f64,
    pub vz: f64,
}

impl Quaternion {
    pub const IDENTITY: Quaternion = Quaternion { w: 1.0, vx: 0.0, vy: 0.0, vz: 0.0 };

    pub fn from(w: f64, vx: f64, vy: f64, vz: f64) -> Quaternion {
        Quaternion { w, vx, vy, vz }
    }

    /// From a rotation axis and an angle (util.cpp `Quaternion::From(Vector axis, double dtheta)`).
    pub fn from_axis_angle(axis: Vector, dtheta: f64) -> Quaternion {
        let c = (dtheta / 2.0).cos();
        let s = (dtheta / 2.0).sin();
        let axis = axis.with_magnitude(s);
        Quaternion { w: c, vx: axis.x, vy: axis.y, vz: axis.z }
    }

    /// From the first two rows [u' v' n']' of the rotation matrix generated by this
    /// quaternion (util.cpp `Quaternion::From(Vector u, Vector v)`).
    pub fn from_rows(u: Vector, v: Vector) -> Quaternion {
        let n = u.cross(v);

        let tr = 1.0 + u.x + v.y + n.z;
        let q = if tr > 1e-4 {
            let s = 2.0 * tr.sqrt();
            Quaternion {
                w: s / 4.0,
                vx: (v.z - n.y) / s,
                vy: (n.x - u.z) / s,
                vz: (u.y - v.x) / s,
            }
        } else if u.x > v.y && u.x > n.z {
            let s = 2.0 * (1.0 + u.x - v.y - n.z).sqrt();
            Quaternion {
                w: (v.z - n.y) / s,
                vx: s / 4.0,
                vy: (u.y + v.x) / s,
                vz: (n.x + u.z) / s,
            }
        } else if v.y > n.z {
            let s = 2.0 * (1.0 - u.x + v.y - n.z).sqrt();
            Quaternion {
                w: (n.x - u.z) / s,
                vx: (u.y + v.x) / s,
                vy: s / 4.0,
                vz: (v.z + n.y) / s,
            }
        } else {
            let s = 2.0 * (1.0 - u.x - v.y + n.z).sqrt();
            Quaternion {
                w: (u.y - v.x) / s,
                vx: (n.x + u.z) / s,
                vy: (v.z + n.y) / s,
                vz: s / 4.0,
            }
        };

        q.with_magnitude(1.0)
    }

    pub fn plus(self, b: Quaternion) -> Quaternion {
        Quaternion { w: self.w + b.w, vx: self.vx + b.vx, vy: self.vy + b.vy, vz: self.vz + b.vz }
    }

    pub fn minus(self, b: Quaternion) -> Quaternion {
        Quaternion { w: self.w - b.w, vx: self.vx - b.vx, vy: self.vy - b.vy, vz: self.vz - b.vz }
    }

    pub fn scaled_by(self, s: f64) -> Quaternion {
        Quaternion { w: self.w * s, vx: self.vx * s, vy: self.vy * s, vz: self.vz * s }
    }

    pub fn magnitude(self) -> f64 {
        (self.w * self.w + self.vx * self.vx + self.vy * self.vy + self.vz * self.vz).sqrt()
    }

    pub fn with_magnitude(self, s: f64) -> Quaternion {
        self.scaled_by(s / self.magnitude())
    }

    /// The first row of the rotation matrix [ u' v' n' ]' generated by this quaternion.
    pub fn rotation_u(self) -> Vector {
        Vector {
            x: self.w * self.w + self.vx * self.vx - self.vy * self.vy - self.vz * self.vz,
            y: 2.0 * self.w * self.vz + 2.0 * self.vx * self.vy,
            z: 2.0 * self.vx * self.vz - 2.0 * self.w * self.vy,
        }
    }

    /// The second row of the rotation matrix [ u' v' n' ]' generated by this quaternion.
    pub fn rotation_v(self) -> Vector {
        Vector {
            x: 2.0 * self.vx * self.vy - 2.0 * self.w * self.vz,
            y: self.w * self.w - self.vx * self.vx + self.vy * self.vy - self.vz * self.vz,
            z: 2.0 * self.w * self.vx + 2.0 * self.vy * self.vz,
        }
    }

    /// The third row of the rotation matrix [ u' v' n' ]' generated by this quaternion.
    pub fn rotation_n(self) -> Vector {
        Vector {
            x: 2.0 * self.w * self.vy + 2.0 * self.vx * self.vz,
            y: 2.0 * self.vy * self.vz - 2.0 * self.w * self.vx,
            z: self.w * self.w - self.vx * self.vx - self.vy * self.vy + self.vz * self.vz,
        }
    }

    pub fn rotate(self, p: Vector) -> Vector {
        self.rotation_u().scaled_by(p.x)
            .plus(self.rotation_v().scaled_by(p.y))
            .plus(self.rotation_n().scaled_by(p.z))
    }

    pub fn to_the(self, p: f64) -> Quaternion {
        if self.w >= 1.0 - 1e-6 {
            Quaternion::from(1.0, 0.0, 0.0, 0.0)
        } else if self.w <= -1.0 + 1e-6 {
            Quaternion::from(-1.0, 0.0, 0.0, 0.0)
        } else {
            let theta = self.w.acos() * p;
            let axis = Vector::from(self.vx, self.vy, self.vz).with_magnitude(theta.sin());
            Quaternion { w: theta.cos(), vx: axis.x, vy: axis.y, vz: axis.z }
        }
    }

    pub fn inverse(self) -> Quaternion {
        Quaternion { w: self.w, vx: -self.vx, vy: -self.vy, vz: -self.vz }.with_magnitude(1.0)
    }

    pub fn times(self, b: Quaternion) -> Quaternion {
        let sa = self.w;
        let sb = b.w;
        let va = Vector::from(self.vx, self.vy, self.vz);
        let vb = Vector::from(b.vx, b.vy, b.vz);

        let vr = vb.scaled_by(sa).plus(va.scaled_by(sb).plus(va.cross(vb)));
        Quaternion { w: sa * sb - va.dot(vb), vx: vr.x, vy: vr.y, vz: vr.z }
    }

    pub fn mirror(self) -> Quaternion {
        let u = self.rotation_u().scaled_by(-1.0);
        let v = self.rotation_v().scaled_by(-1.0);
        Quaternion::from_rows(u, v)
    }
}

/// A 3-vector of real numbers (translated from `Vector`).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Vector {
    pub x: f64,
    pub y: f64,
    pub z: f64,
}

impl Vector {
    pub fn from(x: f64, y: f64, z: f64) -> Vector {
        Vector { x, y, z }
    }

    pub fn element(self, i: usize) -> f64 {
        match i {
            0 => self.x,
            1 => self.y,
            2 => self.z,
            _ => panic!("Unexpected vector element index"),
        }
    }

    pub fn equals(self, v: Vector, tol: f64) -> bool {
        let dv = self.minus(v);
        if dv.x.abs() > tol { return false; }
        if dv.y.abs() > tol { return false; }
        if dv.z.abs() > tol { return false; }
        dv.mag_squared() < tol * tol
    }

    pub fn equals_tol(self, v: Vector) -> bool {
        self.equals(v, LENGTH_EPS)
    }

    pub fn equals_exactly(self, v: Vector) -> bool {
        self.x == v.x && self.y == v.y && self.z == v.z
    }

    pub fn plus(self, b: Vector) -> Vector {
        Vector { x: self.x + b.x, y: self.y + b.y, z: self.z + b.z }
    }

    pub fn minus(self, b: Vector) -> Vector {
        Vector { x: self.x - b.x, y: self.y - b.y, z: self.z - b.z }
    }

    pub fn negated(self) -> Vector {
        Vector { x: -self.x, y: -self.y, z: -self.z }
    }

    pub fn cross(self, b: Vector) -> Vector {
        Vector {
            x: -(self.z * b.y) + (self.y * b.z),
            y: (self.z * b.x) - (self.x * b.z),
            z: -(self.y * b.x) + (self.x * b.y),
        }
    }

    pub fn direction_cosine_with(self, b: Vector) -> f64 {
        let a = self.with_magnitude(1.0);
        let b = b.with_magnitude(1.0);
        a.dot(b)
    }

    pub fn dot(self, b: Vector) -> f64 {
        self.x * b.x + self.y * b.y + self.z * b.z
    }

    /// Arbitrarily choose one vector that's normal to us, pivoting appropriately
    /// (util.cpp `Vector::Normal`).
    pub fn normal(self, which: usize) -> Vector {
        let mut n;
        let xa = self.x.abs();
        let ya = self.y.abs();
        let za = self.z.abs();
        if self.equals_tol(Vector::from(0.0, 0.0, 1.0)) {
            n = Vector::from(1.0, 0.0, 0.0);
        } else if xa < ya && xa < za {
            n = Vector { x: 0.0, y: self.z, z: -self.y };
        } else if ya < za {
            n = Vector { x: -self.z, y: 0.0, z: self.x };
        } else {
            n = Vector { x: self.y, y: -self.x, z: 0.0 };
        }

        if which == 0 {
            // That's the vector we return.
        } else if which == 1 {
            n = self.cross(n);
        } else {
            panic!("Unexpected vector normal index");
        }

        n.with_magnitude(1.0)
    }

    pub fn rotated_about_orig(self, orig: Vector, axis: Vector, theta: f64) -> Vector {
        let r = self.minus(orig).rotated_about(axis, theta);
        r.plus(orig)
    }

    pub fn rotated_about(self, axis: Vector, theta: f64) -> Vector {
        let c = theta.cos();
        let s = theta.sin();
        let axis = axis.with_magnitude(1.0);

        Vector {
            x: self.x * (c + (1.0 - c) * axis.x * axis.x)
                + self.y * ((1.0 - c) * axis.x * axis.y - s * axis.z)
                + self.z * ((1.0 - c) * axis.x * axis.z + s * axis.y),
            y: self.x * ((1.0 - c) * axis.y * axis.x + s * axis.z)
                + self.y * (c + (1.0 - c) * axis.y * axis.y)
                + self.z * ((1.0 - c) * axis.y * axis.z - s * axis.x),
            z: self.x * ((1.0 - c) * axis.z * axis.x - s * axis.y)
                + self.y * ((1.0 - c) * axis.z * axis.y + s * axis.x)
                + self.z * (c + (1.0 - c) * axis.z * axis.z),
        }
    }

    pub fn dot_in_to_csys(self, u: Vector, v: Vector, n: Vector) -> Vector {
        Vector::from(self.dot(u), self.dot(v), self.dot(n))
    }

    pub fn scale_out_of_csys(self, u: Vector, v: Vector, n: Vector) -> Vector {
        u.scaled_by(self.x).plus(v.scaled_by(self.y).plus(n.scaled_by(self.z)))
    }

    pub fn in_perspective(self, u: Vector, v: Vector, n: Vector, origin: Vector, camera_tan: f64) -> Vector {
        let r = self.minus(origin).dot_in_to_csys(u, v, n);
        let w = 1.0 - r.z * camera_tan;
        r.scaled_by(1.0 / w)
    }

    pub fn distance_to_line(self, p0: Vector, dp: Vector) -> f64 {
        let m = dp.magnitude();
        (self.minus(p0)).cross(dp).magnitude() / m
    }

    pub fn distance_to_plane(self, normal: Vector, origin: Vector) -> f64 {
        self.dot(normal) - origin.dot(normal)
    }

    pub fn on_line_segment(self, a: Vector, b: Vector, tol: f64) -> bool {
        if self.equals(a, tol) || self.equals(b, tol) { return true; }

        let d = b.minus(a);
        let m = d.mag_squared();
        let distsq = (self.minus(a)).cross(d).mag_squared() / m;
        if distsq >= tol * tol { return false; }

        let t = (self.minus(a)).div_projected(d);
        if t < 0.0 || t > 1.0 { return false; }
        true
    }

    pub fn closest_point_on_line(self, p0: Vector, dp: Vector) -> Vector {
        let dp = dp.with_magnitude(1.0);
        let pn = (self.minus(p0)).cross(dp);
        let n = pn.cross(dp);
        let d = dp.cross(p0.minus(self)).magnitude();
        self.plus(n.with_magnitude(d))
    }

    pub fn magnitude(self) -> f64 {
        (self.x * self.x + self.y * self.y + self.z * self.z).sqrt()
    }

    pub fn mag_squared(self) -> f64 {
        self.x * self.x + self.y * self.y + self.z * self.z
    }

    pub fn with_magnitude(self, v: f64) -> Vector {
        let m = self.magnitude();
        if m == 0.0 {
            Vector::from(0.0, 0.0, 0.0)
        } else {
            self.scaled_by(v / m)
        }
    }

    pub fn scaled_by(self, v: f64) -> Vector {
        Vector { x: self.x * v, y: self.y * v, z: self.z * v }
    }

    pub fn project_2d(self, u: Vector, v: Vector) -> Point2d {
        Point2d { x: self.dot(u), y: self.dot(v) }
    }

    pub fn project_xy(self) -> Point2d {
        Point2d { x: self.x, y: self.y }
    }

    pub fn project_4d(self) -> Vector4 {
        Vector4::from(1.0, self.x, self.y, self.z)
    }

    pub fn div_projected(self, delta: Vector) -> f64 {
        (self.x * delta.x + self.y * delta.y + self.z * delta.z)
            / (delta.x * delta.x + delta.y * delta.y + delta.z * delta.z)
    }

    pub fn closest_ortho(self) -> Vector {
        let mx = self.x.abs();
        let my = self.y.abs();
        let mz = self.z.abs();

        if mx > my && mx > mz {
            Vector::from(if self.x > 0.0 { 1.0 } else { -1.0 }, 0.0, 0.0)
        } else if my > mz {
            Vector::from(0.0, if self.y > 0.0 { 1.0 } else { -1.0 }, 0.0)
        } else {
            Vector::from(0.0, 0.0, if self.z > 0.0 { 1.0 } else { -1.0 })
        }
    }

    pub fn make_max_min(self, maxv: &mut Vector, minv: &mut Vector) {
        if self.x > maxv.x { maxv.x = self.x; }
        if self.y > maxv.y { maxv.y = self.y; }
        if self.z > maxv.z { maxv.z = self.z; }

        if self.x < minv.x { minv.x = self.x; }
        if self.y < minv.y { minv.y = self.y; }
        if self.z < minv.z { minv.z = self.z; }
    }

    pub fn clamp_within(self, minv: f64, maxv: f64) -> Vector {
        let mut ret = self;
        if ret.x < minv { ret.x = minv; }
        if ret.y < minv { ret.y = minv; }
        if ret.z < minv { ret.z = minv; }
        if ret.x > maxv { ret.x = maxv; }
        if ret.y > maxv { ret.y = maxv; }
        if ret.z > maxv { ret.z = maxv; }
        ret
    }

    pub fn outside_and_not_on(self, maxv: Vector, minv: Vector) -> bool {
        (self.x > maxv.x + LENGTH_EPS) || (self.x < minv.x - LENGTH_EPS)
            || (self.y > maxv.y + LENGTH_EPS) || (self.y < minv.y - LENGTH_EPS)
            || (self.z > maxv.z + LENGTH_EPS) || (self.z < minv.z - LENGTH_EPS)
    }

    pub fn bounding_boxes_disjoint(amax: Vector, amin: Vector, bmax: Vector, bmin: Vector) -> bool {
        for i in 0..3 {
            if amax.element(i) < bmin.element(i) - LENGTH_EPS { return true; }
            if amin.element(i) > bmax.element(i) + LENGTH_EPS { return true; }
        }
        false
    }

    /// Intersection of the two planes n1 dot p = d1, n2 dot p = d2 (util.cpp).
    pub fn at_intersection_of_planes(n1: Vector, d1: f64, n2: Vector, d2: f64) -> Vector {
        let det = n1.dot(n1) * n2.dot(n2) - n1.dot(n2) * n1.dot(n2);
        let c1 = (d1 * n2.dot(n2) - d2 * n1.dot(n2)) / det;
        let c2 = (d2 * n1.dot(n1) - d1 * n1.dot(n2)) / det;
        n1.scaled_by(c1).plus(n2.scaled_by(c2))
    }

    /// Closest points on two (possibly skew) lines; returns (ta, tb)
    /// (util.cpp `ClosestPointBetweenLines`).
    pub fn closest_point_between_lines(
        a0: Vector, da: Vector, b0: Vector, db: Vector,
    ) -> (f64, f64) {
        let dn = da.cross(db);
        let dna = dn.cross(da);
        let dnb = dn.cross(db);

        let tb = ((a0.minus(b0)).dot(dna)) / (db.dot(dna));
        let ta = -((a0.minus(b0)).dot(dnb)) / (da.dot(dnb));
        (ta, tb)
    }

    /// Intersection of two lines, in 3d. This returns the point on the first line
    /// that is closest to the second line (util.cpp `AtIntersectionOfLines`).
    pub fn at_intersection_of_lines(
        a0: Vector, a1: Vector, b0: Vector, b1: Vector,
        skew: &mut bool, parama: &mut f64, paramb: &mut f64,
    ) -> Vector {
        let da = a1.minus(a0);
        let db = b1.minus(b0);

        let (pa, pb) = Vector::closest_point_between_lines(a0, da, b0, db);

        // Check for degenerate line
        if da.mag_squared() < LENGTH_EPS * LENGTH_EPS {
            *skew = true;
            *parama = 0.0;
            *paramb = 0.0;
            return Vector::from(0.0, 0.0, 0.0);
        }

        let p = a0.plus(da.scaled_by(pa));

        *skew = !(p.minus(b0.plus(db.scaled_by(pb))).equals_tol(Vector::from(0.0, 0.0, 0.0)));
        *parama = pa;
        *paramb = pb;
        p
    }

    /// Intersection of a plane and a line; `parallel` reports whether they were
    /// parallel (util.cpp `AtIntersectionOfPlaneAndLine`).
    pub fn at_intersection_of_plane_and_line(
        n: Vector, d: f64, p0: Vector, p1: Vector, parallel: &mut bool,
    ) -> Vector {
        let dp = p1.minus(p0);

        let mut t = 0.0;
        if n.dot(dp).abs() < LENGTH_EPS {
            *parallel = true;
            return Vector::from(0.0, 0.0, 0.0);
        }
        *parallel = false;
        t = (d - n.dot(p0)) / n.dot(dp);

        return p0.plus(dp.scaled_by(t));
    }
}

/// A 4-vector of real numbers; homogeneous coordinates (translated from `Vector4`).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Vector4 {
    pub w: f64,
    pub x: f64,
    pub y: f64,
    pub z: f64,
}

impl Vector4 {
    pub fn from(w: f64, x: f64, y: f64, z: f64) -> Vector4 {
        Vector4 { w, x, y, z }
    }

    pub fn from_v3(w: f64, v: Vector) -> Vector4 {
        Vector4 { w, x: v.x, y: v.y, z: v.z }
    }

    pub fn blend(a: Vector4, b: Vector4, t: f64) -> Vector4 {
        Vector4 {
            w: a.w + (b.w - a.w) * t,
            x: a.x + (b.x - a.x) * t,
            y: a.y + (b.y - a.y) * t,
            z: a.z + (b.z - a.z) * t,
        }
    }

    pub fn plus(self, b: Vector4) -> Vector4 {
        Vector4 { w: self.w + b.w, x: self.x + b.x, y: self.y + b.y, z: self.z + b.z }
    }

    pub fn minus(self, b: Vector4) -> Vector4 {
        Vector4 { w: self.w - b.w, x: self.x - b.x, y: self.y - b.y, z: self.z - b.z }
    }

    pub fn scaled_by(self, s: f64) -> Vector4 {
        Vector4 { w: self.w * s, x: self.x * s, y: self.y * s, z: self.z * s }
    }

    pub fn perspective_project(self) -> Vector {
        if self.w == 0.0 {
            Vector::from(0.0, 0.0, 0.0)
        } else {
            Vector::from(self.x / self.w, self.y / self.w, self.z / self.w)
        }
    }
}

/// A point in 2d (translated from `Point2d`).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Point2d {
    pub x: f64,
    pub y: f64,
}

impl Point2d {
    pub fn from(x: f64, y: f64) -> Point2d {
        Point2d { x, y }
    }

    pub fn from_polar(r: f64, a: f64) -> Point2d {
        Point2d { x: r * a.cos(), y: r * a.sin() }
    }

    pub fn plus(self, b: Point2d) -> Point2d {
        Point2d { x: self.x + b.x, y: self.y + b.y }
    }

    pub fn minus(self, b: Point2d) -> Point2d {
        Point2d { x: self.x - b.x, y: self.y - b.y }
    }

    pub fn scaled_by(self, s: f64) -> Point2d {
        Point2d { x: self.x * s, y: self.y * s }
    }

    pub fn div_projected(self, delta: Point2d) -> f64 {
        (self.x * delta.x + self.y * delta.y) / (delta.x * delta.x + delta.y * delta.y)
    }

    pub fn dot(self, p: Point2d) -> f64 {
        self.x * p.x + self.y * p.y
    }

    pub fn distance_to(self, p: Point2d) -> f64 {
        (self.minus(p)).magnitude()
    }

    pub fn distance_to_line(self, p0: Point2d, dp: Point2d, as_segment: bool) -> f64 {
        // Translated literally from Point2d::DistanceToLine (util.cpp).
        let m = dp.x * dp.x + dp.y * dp.y;
        if m < LENGTH_EPS * LENGTH_EPS {
            return VERY_POSITIVE;
        }

        // Let our line be p = p0 + t*dp, for a scalar t from 0 to 1
        let t = (dp.x * (self.x - p0.x) + dp.y * (self.y - p0.y)) / m;

        if as_segment {
            if t < 0.0 {
                return self.distance_to(p0);
            }
            if t > 1.0 {
                return self.distance_to(p0.plus(dp));
            }
        }
        let closest = p0.plus(dp.scaled_by(t));
        self.distance_to(closest)
    }

    pub fn distance_to_line_signed(self, p0: Point2d, dp: Point2d, as_segment: bool) -> f64 {
        // Translated literally from Point2d::DistanceToLineSigned (util.cpp).
        let m = dp.x * dp.x + dp.y * dp.y;
        if m < LENGTH_EPS * LENGTH_EPS {
            return VERY_POSITIVE;
        }

        let n = dp.normal().with_magnitude(1.0);
        let dist = n.dot(self) - n.dot(p0);
        if as_segment {
            // Let our line be p = p0 + t*dp, for a scalar t from 0 to 1
            let t = (dp.x * (self.x - p0.x) + dp.y * (self.y - p0.y)) / m;
            let sign = if dist > 0.0 { 1.0 } else { -1.0 };
            if t < 0.0 {
                return self.distance_to(p0) * sign;
            }
            if t > 1.0 {
                return self.distance_to(p0.plus(dp)) * sign;
            }
        }

        dist
    }

    pub fn angle(self) -> f64 {
        self.y.atan2(self.x)
    }

    pub fn angle_to(self, p: Point2d) -> f64 {
        (p.minus(self)).angle()
    }

    pub fn magnitude(self) -> f64 {
        (self.x * self.x + self.y * self.y).sqrt()
    }

    pub fn magnitude_squared(self) -> f64 {
        self.x * self.x + self.y * self.y
    }

    pub fn with_magnitude(self, v: f64) -> Point2d {
        let m = self.magnitude();
        if m == 0.0 {
            Point2d::from(0.0, 0.0)
        } else {
            self.scaled_by(v / m)
        }
    }

    pub fn normal(self) -> Point2d {
        Point2d { x: self.y, y: -self.x }
    }

    pub fn equals(self, v: Point2d, tol: f64) -> bool {
        // Translated literally from Point2d::Equals (util.cpp).
        let dx = v.x - self.x;
        if dx < -tol || dx > tol { return false; }
        let dy = v.y - self.y;
        if dy < -tol || dy > tol { return false; }
        self.minus(v).magnitude_squared() < tol * tol
    }
}
